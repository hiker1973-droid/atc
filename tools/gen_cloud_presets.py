# -*- coding: utf-8 -*-
"""Generate pkg/miz/cloud_presets.go from DCS's Config/Effects/clouds.lua.

A mission with a cloud preset stores density 0 plus the preset name and a base;
the layers live in DCS's clouds.lua, not the .miz. This turns each preset into
its layers (bottom altitude in metres, METAR cover) so SkyEye can work out a
ceiling (pkg/miz/weather.go).

Cover per layer: the preset's own "--ATX_METAR" comment when it has one group
per visible layer (the ATMOS-X presets mostly do), else from the layer's
coverage: >= 0.85 OVC, >= 0.6 BKN, >= 0.4 SCT, > 0 FEW. Layers with coverage
0 are not clouds and are dropped.

Run:  python -I tools/gen_cloud_presets.py ["<DCS>/Config/Effects/clouds.lua"]
"""
import os
import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else r"C:\Program Files\Eagle Dynamics\DCS World\Config\Effects\clouds.lua"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "pkg", "miz", "cloud_presets.go")


def cover_from(c):
    if c >= 0.85:
        return "OVC"
    if c >= 0.6:
        return "BKN"
    if c >= 0.4:
        return "SCT"
    return "FEW"


src = open(SRC, encoding="utf-8", errors="replace").read()
version = ""
cfg = os.path.join(os.path.dirname(SRC), "..", "..", "autoupdate.cfg")
if os.path.exists(cfg):
    m = re.search(r'"version":\s*"([^"]+)"', open(cfg, encoding="utf-8", errors="replace").read())
    version = m.group(1) if m else ""

presets = []
for m in re.finditer(r"\n[ \t]*(\w*Preset\d+)\s*=\s*\n[ \t]*\{", src):
    name = m.group(1)
    i, depth = m.end(), 1
    while depth:
        depth += {"{": 1, "}": -1}.get(src[i], 0)
        i += 1
    body = src[m.end():i]
    short = re.search(r"readableNameShort\s*=\s*_\('([^']*)'", body)
    metar = re.search(r"--\s*ATX_METAR\s*(.*)", body)
    groups = re.findall(r"\b(FEW|SCT|BKN|OVC)\d+", metar.group(1)) if metar else []
    layers = [(float(a), float(c)) for a, c in
              re.findall(r"altitudeMin\s*=\s*([\d.]+).*?coverage\s*=\s*([\d.]+)", body, re.S)]
    if not layers:
        continue
    first = layers[0][0]
    vis = sorted([(a, c) for a, c in layers if c > 0])
    if len(groups) == len(vis):
        cov = [(a, g) for (a, _), g in zip(vis, groups)]
    else:
        cov = [(a, cover_from(c)) for a, c in vis]
    presets.append((name, short.group(1).strip() if short else "", first, cov))

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Code generated by tools/gen_cloud_presets.py from DCS %s Config/Effects/clouds.lua. DO NOT EDIT.\n\n" % version)
    f.write("package miz\n\n")
    f.write("// cloudPresets: each DCS cloud preset's layers, bottom up. First is the\n"
            "// preset's first layer altitude (m); a mission's base moves every layer by\n"
            "// base - First.\n")
    f.write("var cloudPresets = map[string]cloudPreset{\n")
    for name, short, first, cov in presets:
        ls = ", ".join('{%d, "%s"}' % (round(a), c) for a, c in cov)
        f.write('\t"%s": {"%s", %d, []cloudLayer{%s}},\n' % (name, short.replace('"', "'"), round(first), ls))
    f.write("}\n")
print("ok", len(presets), "presets ->", os.path.normpath(OUT))
