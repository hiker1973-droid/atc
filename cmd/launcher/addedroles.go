// Stations added on the Settings page that run as their own atc.exe - a
// second AWACS or a second Command (operator 2026-10-25: "in addition to
// tanker add JTAC, COMMAND or other"). The launcher writes them into
// start_added_<theatre>.bat, so they are roles like any other: listed on the
// dashboard, started with the theatre (startRegion), stopped with it, and
// restarted by "Restart this theatre's roles".
//
// Each line is the theatre's own AWACS or Command line with what must differ
// changed: frequency, name and voices; --added-station (its own instance, and
// roles.json's changes for the theatre's own are not applied to it); its own
// log. A second Command also drops the tankers, JTACs, Overlord, Marshal
// handoffs and tower-handoff calls, which stay with the first. The bat's
// environment lines (SRS, EAM, Tacview) are copied from the source bat, so it
// starts the way the theatre's own does on this PC.

const addedMarker = ":: GENERATED by Readback ATC Settings > Roles (stations added there). Rewritten on every change: change them in Settings, not here."

var reLogName = regexp.MustCompile(`--log-name[ =]([A-Za-z0-9-]+)`)

func addedBat(theatre string) string { return "start_added_" + theatre + ".bat" }

func nonzeroFreq(s string) bool { return atof(s) != 0 }

// isAddedRole: a role from start_added_<theatre>.bat.
func isAddedRole(r Role) bool { return strings.Contains(r.cmd, "--added-station") }

// startAddedBat starts the theatre's added stations, if it has any.
func startAddedBat(theatre string) {
	full := filepath.Join(rootDir, addedBat(theatre))
	if _, err := os.Stat(full); err != nil {
		return
	}
	cmd := exec.Command("cmd", "/c", "start", "", full)
	cmd.Dir = rootDir
	_ = cmd.Start()
}

func addedTitle(a rolecfg.AddedStation, theatre string) string {
	kind := "AWACS"
	if a.Kind == rolecfg.AddedCommand {
		kind = "Command"
	}
	return fmt.Sprintf("Added %s %s (%s)", kind, a.Name, theatreLabel(theatre))
}

// sourceRole is the theatre's own GCI or Command role, whose line an added
// one is made from.
func sourceRole(theatre, owner string) (Role, bool) {
	rolesMu.Lock()
	defer rolesMu.Unlock()
	for _, r := range roles {
		if r.Region == theatre && r.cmd != "" && !isAddedRole(r) && rolecfg.OwnerOf(batFlags(r)) == owner {
			return r, true
		}
	}
	return Role{}, false
}

// batHeader is a bat's lines before its first start line: the environment
// it sets up (comments and "@echo off" left out).
func batHeader(bat string) []string {
	b, err := os.ReadFile(filepath.Join(rootDir, bat))
	if err != nil {
		return nil
	}
	var out []string
	for _, line := range strings.Split(strings.ReplaceAll(string(b), "\r\n", "\n"), "\n") {
		t := strings.ToLower(strings.TrimSpace(line))
		if strings.HasPrefix(t, "start ") {
			break
		}
		if t == "" || t == "@echo off" || strings.HasPrefix(t, "::") || strings.HasPrefix(t, "rem ") || t == "rem" {
			continue
		}
		out = append(out, line)
	}
	return out
}

// addedCmd rewrites the source role's command line for an added station.
func addedCmd(src Role, a rolecfg.AddedStation) string {
	toks := splitCmdLine(src.cmd)
	if len(toks) == 0 {
		return ""
	}
	drop := func(name string) bool {
		switch a.Kind {
		case rolecfg.AddedGCI:
			switch name {
			case "gci-callsign", "gci-freq", "gci-voice", "elevenlabs-gci-voice":
				return true
			}
		case rolecfg.AddedCommand:
			switch name {
			case "command-freq", "command-name", "command-voice", "elevenlabs-command-voice", "handoff-marshal-freq", "handoff-watch":
				return true
			}
			for _, p := range []string{"jtac", "tanker", "overlord", "elevenlabs-jtac", "elevenlabs-tanker", "elevenlabs-overlord", "voice-style-jtac"} {
				if strings.HasPrefix(name, p) {
					return true
				}
			}
		}
		switch name {
		case "pprof-port", "dashboard-port", "added-station", "log-name":
			return true
		}
		return false
	}
	out := []string{toks[0]}
	for i := 1; i < len(toks); i++ {
		t := toks[i]
		if !strings.HasPrefix(t, "--") {
			out = append(out, t) // %TACVIEW_FLAG% and the like
			continue
		}
		name, hasValue := strings.TrimPrefix(t, "--"), false
		if j := strings.IndexByte(name, '='); j >= 0 {
			name, hasValue = name[:j], true
		}
		// The next token is this flag's value unless it is a flag, or a
		// %X_FLAG% that stands for flags of its own.
		takesNext := !hasValue && i+1 < len(toks) && !strings.HasPrefix(toks[i+1], "--") &&
			!strings.HasSuffix(strings.ToUpper(toks[i+1]), "_FLAG%")
		if drop(name) {
			if takesNext {
				i++
			}
			continue
		}
		out = append(out, t)
		if takesNext {
			i++
			out = append(out, toks[i])
		}
	}
	freq := strings.TrimRight(strings.TrimRight(fmt.Sprintf("%.3f", a.Freq), "0"), ".")
	switch a.Kind {
	case rolecfg.AddedGCI:
		out = append(out, "--gci-callsign", a.Name, "--gci-freq", freq)
		if a.Voice != "" {
			out = append(out, "--gci-voice", a.Voice)
		}
		if a.Eleven != "" {
			out = append(out, "--elevenlabs-gci-voice", a.Eleven)
		}
		out = append(out, "--log-name", "gci-"+a.ID)
	case rolecfg.AddedCommand:
		out = append(out, "--command-freq", freq, "--command-name", a.Name)
		if a.Voice != "" {
			out = append(out, "--command-voice", a.Voice)
		}
		if a.Eleven != "" {
			out = append(out, "--elevenlabs-command-voice", a.Eleven)
		}
		out = append(out, "--handoff-marshal-freq", "0", "--overlord-name=", "--handoff-watch=false", "--log-name", "command-"+a.ID)
	}
	out = append(out, "--added-station", a.ID)
	for i, t := range out {
		if strings.ContainsAny(t, " \t") {
			out[i] = `"` + t + `"`
		}
	}
	return strings.Join(out, " ")
}

// writeAddedBat writes the theatre's start_added bat from roles.json, or
// removes it when nothing is added. A hand-made file of that name is left alone.
func writeAddedBat(theatre string, th rolecfg.Theatre) error {
	path := filepath.Join(rootDir, addedBat(theatre))
	if b, err := os.ReadFile(path); err == nil && !strings.Contains(string(b), addedMarker) {
		return fmt.Errorf("%s was not written by Readback: rename it, then save again", addedBat(theatre))
	}
	if len(th.Added) == 0 {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return err
		}
		return nil
	}
	lines := []string{"@echo off", addedMarker}
	for _, a := range th.Added {
		owner := rolecfg.OwnerGCI
		if a.Kind == rolecfg.AddedCommand {
			owner = rolecfg.OwnerCommand
		}
		src, ok := sourceRole(theatre, owner)
		if !ok {
			return fmt.Errorf("no %s runs in %s to copy for %s", strings.ToUpper(a.Kind), theatreLabel(theatre), a.Name)
		}
		lines = append(lines, "", ":: "+a.ID+": copied from "+src.Bat)
		lines = append(lines, batHeader(src.Bat)...)
		lines = append(lines, fmt.Sprintf(`start "%s" cmd /c "%s"`, addedTitle(a, theatre), addedCmd(src, a)),
			`%SystemRoot%\System32\timeout.exe /t 3 /nobreak >nul`)
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(strings.Join(lines, "\r\n")+"\r\n"), 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

// stopAddedRole stops a running added station by its id (before it is
// removed or rewritten).
func stopAddedRole(theatre, id string) {
	rolesMu.Lock()
	var name string
	for _, r := range roles {
		if r.Region == theatre && isAddedRole(r) && strings.Contains(r.cmd, "--added-station "+id) {
			name = r.Name
		}
	}
	rolesMu.Unlock()
	if name != "" && len(runningRoles([]string{name})) > 0 {
		_ = stopRole(name)
	}
}

// setJTAC adds a JTAC (prev ""), changes the one called prev, or removes it.
func setJTAC(theatre, prev string, j rolecfg.JTACNet, remove bool) error {
	j.Name, j.Sector, j.Eleven = strings.TrimSpace(j.Name), strings.TrimSpace(j.Sector), strings.TrimSpace(j.Eleven)
	return editTheatre(theatre, func(view theatreRolesView, th *rolecfg.Theatre) error {
		at := -1
		for i, x := range th.JTACs {
			if prev != "" && x.Name == prev {
				at = i
			}
		}
		if prev != "" && at < 0 {
			return fmt.Errorf("no added JTAC %s", prev)
		}
		if remove {
			if at < 0 {
				return fmt.Errorf("which JTAC?")
			}
			th.JTACs = append(th.JTACs[:at:at], th.JTACs[at+1:]...)
			return nil
		}
		if !view.CanJTAC {
			return fmt.Errorf("an added JTAC works beside Hitman 1-1: turn Hitman 1-1 on in %s first", theatreLabel(theatre))
		}
		if err := j.Validate(); err != nil {
			return err
		}
		if taken := nameTaken(view, j.Name, "jtac:"+prev); taken {
			return fmt.Errorf("there is already a station called %s", j.Name)
		}
		if other := freqInUse(view, j.Freq, "jtac:"+prev); other != "" {
			return fmt.Errorf("%.3f is already %s's frequency", j.Freq, other)
		}
		if at >= 0 {
			th.JTACs[at] = j
		} else {
			th.JTACs = append(th.JTACs, j)
		}
		return nil
	})
}

// setAdded adds a second AWACS or Command (prevID ""), changes one, or
// removes it, then rewrites start_added_<theatre>.bat and rescans the roles.
func setAdded(theatre, prevID string, a rolecfg.AddedStation, remove bool) error {
	a.Name, a.Voice, a.Eleven = strings.TrimSpace(a.Name), strings.TrimSpace(a.Voice), strings.TrimSpace(a.Eleven)
	var after rolecfg.Theatre
	err := editTheatre(theatre, func(view theatreRolesView, th *rolecfg.Theatre) error {
		at := -1
		for i, x := range th.Added {
			if prevID != "" && x.ID == prevID {
				at = i
			}
		}
		if prevID != "" && at < 0 {
			return fmt.Errorf("no added station %s", prevID)
		}
		if remove {
			if at < 0 {
				return fmt.Errorf("which station?")
			}
			th.Added = append(th.Added[:at:at], th.Added[at+1:]...)
			after = *th
			return nil
		}
		if at >= 0 {
			a.ID, a.Kind = th.Added[at].ID, th.Added[at].Kind
		}
		if err := a.Validate(); err != nil {
			return err
		}
		if (a.Kind == rolecfg.AddedGCI && !view.CanGCI) || (a.Kind == rolecfg.AddedCommand && !view.CanCommand) {
			return fmt.Errorf("a second one is copied from the theatre's own, and %s has no %s", theatreLabel(theatre), a.Kind)
		}
		if nameTaken(view, a.Name, "added:"+prevID) {
			return fmt.Errorf("there is already a station called %s", a.Name)
		}
		if other := freqInUse(view, a.Freq, "added:"+prevID); other != "" {
			return fmt.Errorf("%.3f is already %s's frequency", a.Freq, other)
		}
		if at >= 0 {
			th.Added[at] = a
		} else {
			used := map[string]bool{}
			for _, x := range th.Added {
				used[x.ID] = true
			}
			for n := 2; ; n++ {
				if id := fmt.Sprintf("%s%d", a.Kind, n); !used[id] {
					a.ID = id
					break
				}
			}
			th.Added = append(th.Added, a)
		}
		after = *th
		return nil
	})
	if err != nil {
		return err
	}
	if prevID != "" {
		stopAddedRole(theatre, prevID) // it comes back with the theatre's restart
	}
	if err := writeAddedBat(theatre, after); err != nil {
		return err
	}
	discoverRoles()
	return nil
}

// nameTaken: a station in the theatre already has this name (self excluded).
func nameTaken(view theatreRolesView, name, self string) bool {
	norm := func(s string) string { return strings.ToLower(strings.ReplaceAll(s, " ", "-")) }
	n := norm(name)
	for _, s := range view.Stations {
		cur := s.Bat.Name
		if s.Override.Name != "" {
			cur = s.Override.Name
		}
		if cur != "" && norm(cur) == n {
			return true
		}
	}
	for _, t := range view.Nets {
		if norm(t.Bat.Name) == n {
			return true
		}
	}
	for _, j := range view.JTACs {
		if "jtac:"+j.Name != self && norm(j.Name) == n {
			return true
		}
	}
	for _, a := range view.Added {
		if "added:"+a.ID != self && norm(a.Name) == n {
			return true
		}
	}
	return false
}
