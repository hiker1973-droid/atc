// Package startgen writes the standard start files a new install gets
// (operator 2026-10-23: "start on the squadron pack"). The vSFG-7 rigs run
// hand-made start bats, months of operator rulings in their comments: the
// vSFG-7 pack, left exactly as it is. A new install has none, so Setup writes
// a standard set for the theatre it picks: ATIS, a tower per field, Command,
// the GCI and, for a carrier squadron, Marshal and Deckboss. From then on the
// frequencies, voices and on/off are the Settings page's.
//
// The text lives here, apart from the launcher that writes it, so cmd/atc's
// tests can check every flag it uses against atc.exe's own.
package startgen

import (
	"fmt"
	"strings"
	"time"

	"github.com/vsfg7/atc/pkg/airfield"
)

// Marker is in every generated file; a bat without it is hand-made and is
// never overwritten.
const Marker = ":: GENERATED by SkyEye Setup"

// Options are Setup's choices for a theatre.
type Options struct {
	Carrier     bool    `json:"carrier"`     // Marshal + Deckboss
	GCI         bool    `json:"gci"`         // the AWACS controller
	GCICallsign string  `json:"gciCallsign"` // e.g. Darkstar
	GCIFreq     float64 `json:"gciFreq"`
}

// Defaults: the GCI on, as Darkstar 264; no carrier.
func Defaults() Options {
	return Options{GCI: true, GCICallsign: "Darkstar", GCIFreq: 264.0}
}

// Check validates options before anything is written.
func (o Options) Check() error {
	if o.GCI && (o.GCICallsign == "" || strings.ContainsAny(o.GCICallsign, " \"%&|<>^") || len(o.GCICallsign) > 20 ||
		o.GCIFreq < 30 || o.GCIFreq > 400) {
		return fmt.Errorf("the GCI needs a one-word callsign and a frequency of 30-400 MHz")
	}
	return nil
}

// RolesBat is the generated roles file; the theatre's region bat calls it.
func RolesBat(theatre string) string { return "start_skyeye_" + theatre + ".bat" }

// towerVoices are handed out in turn, so neighbouring fields sound different.
var towerVoices = []string{"nova", "onyx", "shimmer", "echo", "alloy", "fable", "sage", "ash", "coral"}

const header = `@echo off
%s (%s, %s) - do not edit.
:: Change frequencies, voices and on/off on the launcher's Settings page;
:: run Setup again to rebuild this file.
cd /d %%~dp0
if not defined SKYEYE_SRS (
    echo ERROR: no SRS server set. Open the launcher's Setup page.
    pause
    exit /b 1
)
if not defined SRS_EAM (
    echo ERROR: no SRS password set. Open the launcher's Setup page.
    pause
    exit /b 1
)
set TACVIEW_FLAG=
if defined SKYEYE_TACVIEW set TACVIEW_FLAG=--tacview-addr %%SKYEYE_TACVIEW%%
set MIZ_FLAG=
if defined SKYEYE_MIZ set MIZ_FLAG=--miz-path "%%SKYEYE_MIZ%%"
set GOGC=50
set GOMEMLIMIT=512MiB

`

// RolesText is a theatre's roles bat (LF line ends; the writer makes them CRLF).
func RolesText(theatre, label string, o Options, now time.Time) (string, error) {
	fields := airfield.FieldsForMap(theatre)
	if len(fields) == 0 || airfield.TheatreKey(theatre) != theatre {
		return "", fmt.Errorf("no fields for theatre %q", theatre)
	}
	if err := o.Check(); err != nil {
		return "", err
	}
	var b strings.Builder
	fmt.Fprintf(&b, header, Marker, label, now.Format("2006-01-02"))
	// The SRS flags are written out on every line, as in the hand-made bats:
	// the launcher matches a running atc.exe to its line flag by flag.
	start := func(title, args string) {
		fmt.Fprintf(&b, "start \"%s\" cmd /c \"%%~dp0atc.exe %s --srs-addr %%SKYEYE_SRS%% --eam-password %%SRS_EAM%% --log-level info\"\n", title, args)
		b.WriteString("%SystemRoot%\\System32\\timeout.exe /t 3 /nobreak >nul\n")
	}
	anchor := fields[0].ICAO // Marshal, Deckboss and the GCI only need an --airfield to tell them apart

	start("SkyEye ATIS ("+label+")", "--atis-only --map "+theatre)
	for i, af := range fields {
		args := fmt.Sprintf("--airfield %s --tts-voice %s", af.ICAO, towerVoices[i%len(towerVoices)])
		if p := airfield.DashboardPorts[af.ICAO]; p > 0 {
			args += fmt.Sprintf(" --dashboard-port %d", p)
		}
		start(af.Name+" Tower", args+" --runway-rotation=false %TACVIEW_FLAG% %MIZ_FLAG%")
	}
	marshal := "0"
	if o.Carrier {
		marshal = "306.3"
	}
	cmd := fmt.Sprintf("--command-only --map %s --command-freq 282.0 --command-name SkyEye-Command --command-voice onyx"+
		" --handoff-marshal-freq %s --squadron-range=false %%TACVIEW_FLAG%% %%MIZ_FLAG%%", theatre, marshal)
	if o.GCI {
		cmd += fmt.Sprintf(" --command-gci-name %s --command-gci-freq %.1f", o.GCICallsign, o.GCIFreq)
	}
	start("SkyEye Command ("+label+")", cmd)
	if o.GCI {
		start(fmt.Sprintf("SkyEye GCI %s (%s)", o.GCICallsign, label),
			fmt.Sprintf("--gci-only --map %s --airfield %s --gci-callsign %s --gci-freq %.1f --gci-picture-interval 5m %%TACVIEW_FLAG%%",
				theatre, anchor, o.GCICallsign, o.GCIFreq))
	}
	if o.Carrier {
		start("Marshal ("+label+")", fmt.Sprintf("--marshal-only --airfield %s --marshal-freq 306.3 --handoff-command-name Command --dashboard-port 6004 %%TACVIEW_FLAG%% %%MIZ_FLAG%%", anchor))
		start("Deckboss ("+label+")", fmt.Sprintf("--airfield %s --deckboss-freq 128.6 --handoff-marshal-freq 306.3 --handoff-command-name Command --no-atis --dashboard-port 6005 %%TACVIEW_FLAG%%", anchor))
	}
	return b.String(), nil
}

// RegionText is the theatre's region bat, what the dashboard's Start runs.
func RegionText(theatre, label string, now time.Time) string {
	return fmt.Sprintf("@echo off\n%s (%s, %s) - do not edit.\n:: The theatre's region start: the dashboard's Start button runs this.\ncd /d %%~dp0\ncall \"%%~dp0%s\"\n",
		Marker, label, now.Format("2006-01-02"), RolesBat(theatre))
}
